#!/usr/bin/env python3
"""Build the offline browser engine with WASI SDK 34's Clang (no WASI runtime).

SPDX-License-Identifier: GPL-2.0-or-later
"""
import argparse
import base64
import os
import subprocess
import tempfile
from pathlib import Path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    sdk = os.environ.get('WASI_SDK_PATH')
    if not sdk:
        raise SystemExit('Set WASI_SDK_PATH to an extracted WASI SDK 34 directory; see DEVELOPING.md.')
    with tempfile.TemporaryDirectory(prefix='t9-wasm-') as temp:
        binary = Path(temp) / 'engine.wasm'
        subprocess.run([
            str(Path(sdk) / 'bin' / 'clang'), '--target=wasm32-unknown-unknown',
            '-std=c11', '-Oz', '-Wall', '-Wextra', '-Werror', '-ffreestanding', '-fno-builtin', '-nostdlib',
            '-Idemo/wasm', '-Ikeymap',
            'demo/wasm/bridge.c', 'demo/wasm/strings.c', 'keymap/t9_engine.c', 'keymap/t9_output.c',
            'keymap/t9_contractions.c', 'keymap/t9_dict_packed.c', 'keymap/t9_shortcuts.c',
            '-Wl,--no-entry,--export-memory,--strip-all,-z,stack-size=65536',
            '-Wl,--initial-memory=524288,--max-memory=524288', '-o', str(binary),
        ], cwd=root, check=True)
        encoded = base64.b64encode(binary.read_bytes()).decode('ascii')
    output = (
        '// Generated by demo/build_wasm.py with WASI SDK 34; do not edit.\n'
        '// GPL-2.0-or-later. Includes dictionary data; see ../LICENSES.md.\n'
        f'globalThis.T9_WASM_BASE64 = "{encoded}";\n'
    )
    destination = root / 'demo' / 'engine-wasm.js'
    if args.check:
        if not destination.exists() or destination.read_text() != output:
            raise SystemExit('Browser engine is stale; run python3 demo/build_wasm.py')
        print('Browser engine matches the production sources.')
    else:
        destination.write_text(output)
        print(f'Wrote {destination} ({len(encoded):,} base64 characters).')


if __name__ == '__main__':
    main()
