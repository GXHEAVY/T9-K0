import argparse
import json
import os
import runpy
import shlex
import subprocess
import tempfile
from pathlib import Path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the checked-in recording is stale")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    sources = [
        "demo/export_trace.c",
        "keymap/t9_engine.c",
        "keymap/t9_output.c",
        "keymap/t9_contractions.c",
        "keymap/t9_dict_packed.c",
        "keymap/t9_shortcuts.c",
    ]
    with tempfile.TemporaryDirectory(prefix="t9-demo-") as temporary:
        executable = str(Path(temporary) / "export_trace")
        subprocess.run(
            [
                *shlex.split(os.environ.get("CC", "cc")),
                "-std=c11", "-O2", "-Wall", "-Wextra", "-Werror", "-Ikeymap",
                *sources, "-o", executable,
            ],
            cwd=root,
            check=True,
        )
        data = json.loads(subprocess.check_output([executable], text=True))
    # Share the documented physical-key maps; these are presentation labels,
    # not a browser implementation of the QMK lighting/media/connection controls.
    maps = runpy.run_path(str(root / "keymap_grid.py"))["LAYERS"]
    data["layers"] = {name: maps[name] for name in ("t9", "multitap", "numpad", "slash", "fn")}
    output = (
        "// Generated by demo/generate.py from the production C engine; do not edit.\n"
        "// Source: GPL-2.0-or-later. Dictionary-derived data: see ../LICENSES.md.\n"
        f"window.T9_DEMO_TRACE = {json.dumps(data, ensure_ascii=True, indent=2)};\n"
    )
    destination = root / "demo" / "trace.js"
    if args.check:
        if not destination.exists() or destination.read_text() != output:
            raise SystemExit("Demo trace is stale; run python3 demo/generate.py")
        print(f"Demo trace matches; all {len(data['scenes'])} scenario assertions passed.")
    else:
        destination.write_text(output)
        print(f"Recorded {sum(len(scene['frames']) for scene in data['scenes'])} frames in {destination}")


if __name__ == "__main__":
    main()
